"""
GrammarAgentAPI: programmatic interface used by CLI skills and the DSPy pipeline.

All methods work directly against the in-process GrammarIndex — no IPC.
"""

from __future__ import annotations

import random
from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional

from lsprotocol import types as lsp

from core.index import GrammarIndex, RuleLocation
from core.document import GrammarDocument, _collect_rule_refs_from_expansion
from core.dialect import CustomFunction


# ------------------------------------------------------------------ #
#  Result types                                                        #
# ------------------------------------------------------------------ #

@dataclass
class CoverageResult:
    covered: list[str]
    uncovered: list[str]
    coverage_ratio: float

    def as_dict(self) -> dict:
        return {
            'covered': self.covered,
            'uncovered': self.uncovered,
            'coverage_ratio': self.coverage_ratio,
        }


@dataclass
class RuleAnalysis:
    name: str
    file: str
    visible: bool
    dependencies: list[str]      # rule names this rule references
    dependents: list[str]        # rule names that reference this rule
    example_utterances: list[str]

    def as_dict(self) -> dict:
        return {
            'name': self.name,
            'file': self.file,
            'visible': self.visible,
            'dependencies': self.dependencies,
            'dependents': self.dependents,
            'example_utterances': self.example_utterances,
        }


@dataclass
class GenerationContext:
    existing_rules: list[dict]       # serialisable RuleAnalysis dicts
    dialect_functions: list[dict]    # serialisable function specs
    similar_rules: list[dict]        # top-N rules by utterance overlap
    import_suggestions: list[str]    # file paths worth importing

    def as_dict(self) -> dict:
        return {
            'existing_rules': self.existing_rules,
            'dialect_functions': self.dialect_functions,
            'similar_rules': self.similar_rules,
            'import_suggestions': self.import_suggestions,
        }


# ------------------------------------------------------------------ #
#  API                                                                 #
# ------------------------------------------------------------------ #

class GrammarAgentAPI:
    def __init__(self, index: GrammarIndex):
        self.index = index

    # ---------------------------------------------------------------- #
    #  Expansion sampling                                               #
    # ---------------------------------------------------------------- #

    def get_examples(
        self,
        rule_name: str,
        from_file: Path,
        n: int = 20,
    ) -> list[str]:
        """
        Return up to *n* example utterances generated by *rule_name*.
        Returns [] if the rule is not found or has no parseable expansion.
        """
        loc = self.index.resolve_rule(rule_name, from_file)
        if loc is None or loc.rule.grammar_object is None:
            return []
        try:
            expansions = list(_generate_expansions(
                loc.rule.grammar_object.expansion, self.index, from_file
            ))
        except RecursionError:
            return []
        if not expansions:
            return []
        return random.sample(expansions, min(n, len(expansions)))

    # ---------------------------------------------------------------- #
    #  Coverage                                                         #
    # ---------------------------------------------------------------- #

    def validate_coverage(
        self,
        rule_name: str,
        from_file: Path,
        utterances: list[str],
    ) -> CoverageResult:
        """Check which *utterances* are matched by *rule_name*."""
        loc = self.index.resolve_rule(rule_name, from_file)
        if loc is None or loc.rule.grammar_object is None:
            return CoverageResult([], utterances, 0.0)
        rule_obj = loc.rule.grammar_object
        covered: list[str] = []
        uncovered: list[str] = []
        for u in utterances:
            try:
                matched = rule_obj.matches(u)
            except RecursionError:
                matched = False
            (covered if matched else uncovered).append(u)
        ratio = len(covered) / len(utterances) if utterances else 0.0
        return CoverageResult(covered, uncovered, ratio)

    def find_rules_matching(
        self,
        utterances: list[str],
        scope: Optional[Path] = None,
    ) -> list[tuple[RuleLocation, CoverageResult]]:
        """
        Find rules (optionally within *scope* file) that match any of *utterances*.
        Returns results sorted by coverage ratio descending.
        """
        results: list[tuple[RuleLocation, CoverageResult]] = []
        files = [scope] if scope else list(self.index._documents)
        for f in files:
            doc = self.index._documents.get(f)
            if doc is None:
                continue
            for rule_info in doc.rules:
                cov = self.validate_coverage(rule_info.name, f, utterances)
                if cov.coverage_ratio > 0:
                    results.append((
                        RuleLocation(file=f, rule=rule_info),
                        cov,
                    ))
        results.sort(key=lambda x: x[1].coverage_ratio, reverse=True)
        return results

    # ---------------------------------------------------------------- #
    #  Generation context                                               #
    # ---------------------------------------------------------------- #

    def get_generation_context(
        self,
        target_file: Path,
        description: str,
        examples: list[str],
    ) -> GenerationContext:
        """
        Assemble context for the generation program:
        - visible rules in *target_file*
        - dialect functions
        - top-5 rules by utterance coverage
        - files to consider importing
        """
        existing = [
            self._analyze(loc).as_dict()
            for loc in self.index.get_visible_rules(target_file)
        ]
        matches = self.find_rules_matching(examples)[:5]
        similar = [
            self._analyze(loc).as_dict()
            for loc, cov in matches
            if cov.coverage_ratio > 0.3
        ]
        import_suggestions = list({
            str(loc.file)
            for loc, _ in matches
            if loc.file != target_file
        })
        dialect_functions = [
            {
                'name': fn.name,
                'parameters': [{'name': p.name, 'type': p.type, 'optional': p.optional}
                               for p in fn.parameters],
                'return_type': fn.return_type,
                'doc': fn.doc,
            }
            for fn in self.index.dialect.functions.values()
        ]
        return GenerationContext(
            existing_rules=existing,
            dialect_functions=dialect_functions,
            similar_rules=similar,
            import_suggestions=import_suggestions,
        )

    # ---------------------------------------------------------------- #
    #  Generated grammar validation                                     #
    # ---------------------------------------------------------------- #

    def validate_generated_grammar(
        self,
        source: str,
        target_file: Path,
        required_utterances: list[str],
    ) -> tuple[list[lsp.Diagnostic], Optional[CoverageResult]]:
        """
        Parse *source* as a grammar for *target_file* and validate it.
        Returns (diagnostics, coverage_result).
        coverage_result is None if there are parse errors.
        """
        from core.validator import validate_dialect
        doc = GrammarDocument.parse(target_file, source)
        diags = doc.get_diagnostics(self.index)
        diags += validate_dialect(doc, self.index.dialect)
        if diags:
            return diags, None

        # Find the first public rule for coverage check
        public_rules = [r for r in doc.rules if r.visible]
        if not public_rules:
            return [], CoverageResult([], required_utterances, 0.0)

        # Temporarily index the generated grammar
        self.index.update_file(target_file, source)
        coverage = self.validate_coverage(
            public_rules[0].name, target_file, required_utterances
        )
        return [], coverage

    # ---------------------------------------------------------------- #
    #  Private helpers                                                  #
    # ---------------------------------------------------------------- #

    def _analyze(self, loc: RuleLocation) -> RuleAnalysis:
        """Produce a RuleAnalysis for a located rule."""
        deps: list[str] = []
        if loc.rule.grammar_object is not None:
            deps = _collect_rule_refs_from_expansion(loc.rule.grammar_object.expansion)

        # dependents: rules in other files that reference this rule
        dependents: list[str] = []
        for ref_path, positions in self.index.find_references(loc.rule.name):
            ref_doc = self.index._documents.get(ref_path)
            if ref_doc:
                for r in ref_doc.rules:
                    if r.grammar_object and loc.rule.name in _collect_rule_refs_from_expansion(r.grammar_object.expansion):
                        dependents.append(r.name)

        examples = self.get_examples(loc.rule.name, loc.file, n=5)

        return RuleAnalysis(
            name=loc.rule.name,
            file=str(loc.file),
            visible=loc.rule.visible,
            dependencies=deps,
            dependents=dependents,
            example_utterances=examples,
        )


# ------------------------------------------------------------------ #
#  Expansion generator (bounded)                                       #
# ------------------------------------------------------------------ #

def _generate_expansions(expansion, index: GrammarIndex, from_file: Path, depth: int = 0):
    """
    Recursively yield string expansions of a pyjsgf expansion.
    Bounded to depth 6 to avoid combinatorial explosion.
    """
    from itertools import product
    from jsgf.expansions import (
        AlternativeSet, Sequence, Literal, OptionalGrouping,
        KleeneStar, Repeat, NamedRuleRef, NullRef, VoidRef,
        SingleChildExpansion,
    )

    if depth > 6:
        return

    if isinstance(expansion, Literal):
        yield expansion.text
    elif isinstance(expansion, AlternativeSet):
        for child in expansion.children:
            yield from _generate_expansions(child, index, from_file, depth + 1)
    elif isinstance(expansion, Sequence):
        parts = [
            list(_generate_expansions(c, index, from_file, depth + 1))
            for c in expansion.children
        ]
        for combo in product(*parts):
            joined = ' '.join(p for p in combo if p)
            if joined:
                yield joined
    elif isinstance(expansion, OptionalGrouping):
        yield ''
        yield from _generate_expansions(expansion.child, index, from_file, depth + 1)
    elif isinstance(expansion, (KleeneStar, Repeat)):
        # Yield zero and one repetition to keep it bounded
        yield ''
        yield from _generate_expansions(expansion.child, index, from_file, depth + 1)
    elif isinstance(expansion, NamedRuleRef):
        loc = index.resolve_rule(expansion.name, from_file)
        if loc and loc.rule.grammar_object is not None:
            yield from _generate_expansions(
                loc.rule.grammar_object.expansion, index, from_file, depth + 1
            )
    elif isinstance(expansion, (NullRef, VoidRef)):
        return
    elif isinstance(expansion, SingleChildExpansion):
        yield from _generate_expansions(expansion.child, index, from_file, depth + 1)
    else:
        # Fallback: try children
        for child in getattr(expansion, 'children', []):
            yield from _generate_expansions(child, index, from_file, depth + 1)
