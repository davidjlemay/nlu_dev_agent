"""
GrammarAgentAPI: programmatic interface used by CLI skills and the DSPy pipeline.

All methods work directly against the in-process GrammarIndex — no IPC.
"""

from __future__ import annotations

import random
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional

from lsprotocol import types as lsp

from core.index import GrammarIndex, RuleLocation
from core.document import GrammarDocument, _collect_rule_refs_from_expansion
from core.dialect import CustomFunction
from core.loader import DataLoader


# ------------------------------------------------------------------ #
#  Result types                                                        #
# ------------------------------------------------------------------ #

@dataclass
class CoverageResult:
    covered: list[str]
    uncovered: list[str]
    coverage_ratio: float

    def as_dict(self) -> dict:
        return {
            'covered': self.covered,
            'uncovered': self.uncovered,
            'coverage_ratio': self.coverage_ratio,
        }


@dataclass
class RuleAnalysis:
    name: str
    file: str
    visible: bool
    dependencies: list[str]      # rule names this rule references
    dependents: list[str]        # rule names that reference this rule
    example_utterances: list[str]

    def as_dict(self) -> dict:
        return {
            'name': self.name,
            'file': self.file,
            'visible': self.visible,
            'dependencies': self.dependencies,
            'dependents': self.dependents,
            'example_utterances': self.example_utterances,
        }


@dataclass
class GenerationContext:
    existing_rules: list[dict]       # serialisable RuleAnalysis dicts
    dialect_functions: list[dict]    # serialisable function specs
    similar_rules: list[dict]        # top-N rules by utterance overlap
    import_suggestions: list[str]    # file paths worth importing

    def as_dict(self) -> dict:
        return {
            'existing_rules': self.existing_rules,
            'dialect_functions': self.dialect_functions,
            'similar_rules': self.similar_rules,
            'import_suggestions': self.import_suggestions,
        }


# ------------------------------------------------------------------ #
#  API                                                                 #
# ------------------------------------------------------------------ #

class GrammarAgentAPI:
    def __init__(self, index: GrammarIndex, loader: DataLoader | None = None):
        self.index = index
        self.loader = loader

    # ---------------------------------------------------------------- #
    #  Expansion sampling                                               #
    # ---------------------------------------------------------------- #

    def get_examples(
        self,
        rule_name: str,
        from_file: Path,
        n: int = 20,
    ) -> list[str]:
        """
        Return up to *n* example utterances generated by *rule_name*.
        Returns [] if the rule is not found or has no parseable expansion.
        """
        loc = self.index.resolve_rule(rule_name, from_file)
        if loc is None or loc.rule.grammar_object is None:
            return []
        doc = self.index._documents.get(from_file)
        limit = self.loader.expansion_limit if self.loader else 200
        budget = [limit]
        try:
            expansions = list(_generate_expansions(
                loc.rule.grammar_object.expansion, self.index, from_file,
                loader=self.loader, doc=doc, budget=budget,
            ))
        except RecursionError:
            return []
        if not expansions:
            return []
        return random.sample(expansions, min(n, len(expansions)))

    # ---------------------------------------------------------------- #
    #  Coverage                                                         #
    # ---------------------------------------------------------------- #

    def validate_coverage(
        self,
        rule_name: str,
        from_file: Path,
        utterances: list[str],
    ) -> CoverageResult:
        """Check which *utterances* are matched by *rule_name*.

        Unions coverage across all variants (rules with the same base name but
        different LHS flags) so that an utterance is covered if any variant
        matches it.
        """
        def _try_match(rule_obj, u: str) -> bool:
            try:
                return rule_obj.matches(u)
            except RecursionError:
                return False

        locs = self.index.resolve_rules(rule_name, from_file)
        if not locs:
            loc = self.index.resolve_rule(rule_name, from_file)
            if not loc:
                return CoverageResult([], utterances, 0.0)
            locs = [loc]

        # When the rule uses lookup placeholders and a loader is available,
        # generate all expansions into a set and use set membership.
        doc = self.index._documents.get(from_file)
        use_expansion_path = (
            self.loader is not None
            and doc is not None
            and bool(doc.func_placeholders)
        )
        if use_expansion_path:
            loc = locs[0]
            if loc.rule.grammar_object is not None:
                budget = [self.loader.expansion_limit]  # type: ignore[union-attr]
                try:
                    expansion_set = set(_generate_expansions(
                        loc.rule.grammar_object.expansion, self.index, from_file,
                        loader=self.loader, doc=doc, budget=budget,
                    ))
                except RecursionError:
                    expansion_set = set()
                covered: list[str] = []
                uncovered: list[str] = []
                for u in utterances:
                    (covered if u in expansion_set else uncovered).append(u)
                ratio = len(covered) / len(utterances) if utterances else 0.0
                return CoverageResult(covered, uncovered, ratio)

        rule_objs = [loc.rule.grammar_object for loc in locs if loc.rule.grammar_object]
        if not rule_objs:
            return CoverageResult([], utterances, 0.0)

        covered = []
        uncovered = []
        for u in utterances:
            matched = any(_try_match(rule_obj, u) for rule_obj in rule_objs)
            (covered if matched else uncovered).append(u)
        ratio = len(covered) / len(utterances) if utterances else 0.0
        return CoverageResult(covered, uncovered, ratio)

    def find_rules_matching(
        self,
        utterances: list[str],
        scope: Optional[Path] = None,
    ) -> list[tuple[RuleLocation, CoverageResult]]:
        """
        Find rules (optionally within *scope* file) that match any of *utterances*.
        Returns results sorted by coverage ratio descending.
        """
        results: list[tuple[RuleLocation, CoverageResult]] = []
        files = [scope] if scope else list(self.index._documents)
        for f in files:
            doc = self.index._documents.get(f)
            if doc is None:
                continue
            for rule_info in doc.rules:
                cov = self.validate_coverage(rule_info.name, f, utterances)
                if cov.coverage_ratio > 0:
                    results.append((
                        RuleLocation(file=f, rule=rule_info),
                        cov,
                    ))
        results.sort(key=lambda x: x[1].coverage_ratio, reverse=True)
        return results

    # ---------------------------------------------------------------- #
    #  Generation context                                               #
    # ---------------------------------------------------------------- #

    def get_generation_context(
        self,
        target_file: Path,
        description: str,
        examples: list[str],
    ) -> GenerationContext:
        """
        Assemble context for the generation program:
        - visible rules in *target_file*
        - dialect functions
        - top-5 rules by utterance coverage
        - files to consider importing
        """
        existing = [
            self._analyze(loc).as_dict()
            for loc in self.index.get_visible_rules(target_file)
        ]
        matches = self.find_rules_matching(examples)[:5]
        similar = [
            self._analyze(loc).as_dict()
            for loc, cov in matches
            if cov.coverage_ratio > 0.3
        ]
        import_suggestions = list({
            str(loc.file)
            for loc, _ in matches
            if loc.file != target_file
        })
        dialect_functions = [
            {
                'name': fn.name,
                'parameters': [{'name': p.name, 'type': p.type, 'optional': p.optional}
                               for p in fn.parameters],
                'return_type': fn.return_type,
                'doc': fn.doc,
            }
            for fn in self.index.dialect.functions.values()
        ]
        return GenerationContext(
            existing_rules=existing,
            dialect_functions=dialect_functions,
            similar_rules=similar,
            import_suggestions=import_suggestions,
        )

    # ---------------------------------------------------------------- #
    #  Generated grammar validation                                     #
    # ---------------------------------------------------------------- #

    def validate_generated_grammar(
        self,
        source: str,
        target_file: Path,
        required_utterances: list[str],
    ) -> tuple[list[lsp.Diagnostic], Optional[CoverageResult]]:
        """
        Parse *source* as a grammar for *target_file* and validate it.
        Returns (diagnostics, coverage_result).
        coverage_result is None if there are parse errors.
        """
        from core.validator import validate_dialect
        doc = GrammarDocument.parse(target_file, source)
        diags = doc.get_diagnostics(self.index)
        diags += validate_dialect(doc, self.index.dialect)
        if diags:
            return diags, None

        # Find the first public rule for coverage check
        public_rules = [r for r in doc.rules if r.visible]
        if not public_rules:
            return [], CoverageResult([], required_utterances, 0.0)

        # Temporarily index the generated grammar
        self.index.update_file(target_file, source)
        coverage = self.validate_coverage(
            public_rules[0].name, target_file, required_utterances
        )
        return [], coverage

    # ---------------------------------------------------------------- #
    #  Private helpers                                                  #
    # ---------------------------------------------------------------- #

    def _analyze(self, loc: RuleLocation) -> RuleAnalysis:
        """Produce a RuleAnalysis for a located rule."""
        deps: list[str] = []
        if loc.rule.grammar_object is not None:
            deps = _collect_rule_refs_from_expansion(loc.rule.grammar_object.expansion)

        # dependents: rules in other files that reference this rule
        dependents: list[str] = []
        for ref_path, positions in self.index.find_references(loc.rule.name):
            ref_doc = self.index._documents.get(ref_path)
            if ref_doc:
                for r in ref_doc.rules:
                    if r.grammar_object and loc.rule.name in _collect_rule_refs_from_expansion(r.grammar_object.expansion):
                        dependents.append(r.name)

        examples = self.get_examples(loc.rule.name, loc.file, n=5)

        return RuleAnalysis(
            name=loc.rule.name,
            file=str(loc.file),
            visible=loc.rule.visible,
            dependencies=deps,
            dependents=dependents,
            example_utterances=examples,
        )


# ------------------------------------------------------------------ #
#  Expansion generator (bounded)                                       #
# ------------------------------------------------------------------ #

def _generate_expansions(
    expansion,
    index: GrammarIndex,
    from_file: Path,
    depth: int = 0,
    loader: 'DataLoader | None' = None,
    doc: 'GrammarDocument | None' = None,
    bindings: 'dict[str, str] | None' = None,
    budget: 'list[int] | None' = None,
):
    """
    Recursively yield string expansions of a pyjsgf expansion.
    Bounded to depth 6 to avoid combinatorial explosion.

    loader   — DataLoader for resolving $lookup() placeholders
    doc      — GrammarDocument containing func_placeholders / param_call_sites
    bindings — maps PARM_<name> token → resolved string value (for parameterized rules)
    budget   — mutable [remaining] counter; stops yielding when reaches 0
    """
    from itertools import product
    from jsgf.expansions import (
        AlternativeSet, Sequence, Literal, OptionalGrouping,
        KleeneStar, Repeat, NamedRuleRef, NullRef, VoidRef,
        SingleChildExpansion,
    )

    if depth > 6:
        return

    def _budget_ok() -> bool:
        return budget is None or budget[0] > 0

    def _charge() -> None:
        if budget is not None:
            budget[0] -= 1

    if isinstance(expansion, Literal):
        # pyjsgf lowercases all literal text
        text = expansion.text

        # 1. Param substitution — bindings keys are PARM_<name>, pyjsgf stores
        #    them as parm_<name> (lowercase), so compare lowercase.
        if bindings:
            for token, value in bindings.items():
                text = text.replace(token.lower(), value)

        # 2. Lookup function placeholder expansion — PLHDR<n> tokens may be
        #    embedded inside a longer literal like 'balance of plhdr0'.
        if loader and doc:
            _plhdr_re = re.compile(r'\bplhdr\d+\b')
            plhdr_tokens = _plhdr_re.findall(text)
            if plhdr_tokens:
                parts = _plhdr_re.split(text)
                # Build option lists: literal prefix/suffix interleaved with
                # the loaded values for each PLHDR slot.
                segment_options: list[list[str]] = [
                    [parts[0]] if parts[0] else ['']
                ]
                for i, plhdr_lower in enumerate(plhdr_tokens):
                    fn_info = doc.func_placeholders.get(plhdr_lower.upper())
                    if fn_info:
                        fn_name, fn_args = fn_info
                        if fn_name == 'lookup' and fn_args:
                            loaded = loader.load(fn_args[0])
                            segment_options.append(loaded if loaded else [plhdr_lower])
                        else:
                            segment_options.append([plhdr_lower])
                    else:
                        segment_options.append([plhdr_lower])
                    suffix = parts[i + 1] if i + 1 < len(parts) else ''
                    segment_options.append([suffix] if suffix else [''])
                for combo in product(*segment_options):
                    if not _budget_ok():
                        return
                    result = ''.join(combo).strip()
                    if result:
                        _charge()
                        yield result
                return

        yield text

    elif isinstance(expansion, AlternativeSet):
        for child in expansion.children:
            yield from _generate_expansions(
                child, index, from_file, depth + 1,
                loader=loader, doc=doc, bindings=bindings, budget=budget,
            )
    elif isinstance(expansion, Sequence):
        parts = [
            list(_generate_expansions(
                c, index, from_file, depth + 1,
                loader=loader, doc=doc, bindings=bindings, budget=budget,
            ))
            for c in expansion.children
        ]
        for combo in product(*parts):
            if not _budget_ok():
                return
            joined = ' '.join(p for p in combo if p)
            if joined:
                _charge()
                yield joined
    elif isinstance(expansion, OptionalGrouping):
        yield ''
        yield from _generate_expansions(
            expansion.child, index, from_file, depth + 1,
            loader=loader, doc=doc, bindings=bindings, budget=budget,
        )
    elif isinstance(expansion, (KleeneStar, Repeat)):
        # Yield zero and one repetition to keep it bounded
        yield ''
        yield from _generate_expansions(
            expansion.child, index, from_file, depth + 1,
            loader=loader, doc=doc, bindings=bindings, budget=budget,
        )
    elif isinstance(expansion, NamedRuleRef):
        loc = index.resolve_rule(expansion.name, from_file)
        if loc and loc.rule.grammar_object is not None:
            target_doc = doc
            if loc.file != from_file:
                target_doc = index._documents.get(loc.file)

            # Parameterized rule expansion
            if loc.rule.params and doc is not None:
                call_sites = doc.param_call_sites.get(expansion.name, [])
                if call_sites:
                    for arg_list in call_sites:
                        if not _budget_ok():
                            return
                        # Build bindings: param name → expanded string samples
                        # Each arg is either a rule ref like '<savings>' or literal
                        param_names = loc.rule.params
                        # Pair args to params (truncate to shorter length)
                        pairs = list(zip(param_names, arg_list))
                        # Expand each arg value (strip angle brackets if it's a rule ref)
                        arg_expansions: list[list[str]] = []
                        for _pname, arg_val in pairs:
                            arg_val = arg_val.strip()
                            inner_ref = re.match(r'^<([A-Za-z0-9_.$-]+)>$', arg_val)
                            if inner_ref:
                                ref_loc = index.resolve_rule(inner_ref.group(1), from_file)
                                if ref_loc and ref_loc.rule.grammar_object is not None:
                                    samples = list(_generate_expansions(
                                        ref_loc.rule.grammar_object.expansion,
                                        index, from_file, depth + 1,
                                        loader=loader, doc=doc, bindings=bindings, budget=budget,
                                    ))
                                    arg_expansions.append(samples or [arg_val])
                                else:
                                    arg_expansions.append([inner_ref.group(1)])
                            else:
                                arg_expansions.append([arg_val])
                        # Cross product of arg expansions
                        for arg_combo in product(*arg_expansions):
                            if not _budget_ok():
                                return
                            new_bindings = dict(bindings or {})
                            for (_pname, _), val in zip(pairs, arg_combo):
                                new_bindings[f'PARM_{_pname}'] = val
                            yield from _generate_expansions(
                                loc.rule.grammar_object.expansion,
                                index, loc.file, depth + 1,
                                loader=loader, doc=target_doc,
                                bindings=new_bindings, budget=budget,
                            )
                    return   # handled via call sites
            # Non-parameterized (or no call site info): expand normally
            yield from _generate_expansions(
                loc.rule.grammar_object.expansion, index, loc.file, depth + 1,
                loader=loader, doc=target_doc, bindings=bindings, budget=budget,
            )
    elif isinstance(expansion, (NullRef, VoidRef)):
        return
    elif isinstance(expansion, SingleChildExpansion):
        yield from _generate_expansions(
            expansion.child, index, from_file, depth + 1,
            loader=loader, doc=doc, bindings=bindings, budget=budget,
        )
    else:
        # Fallback: try children
        for child in getattr(expansion, 'children', []):
            yield from _generate_expansions(
                child, index, from_file, depth + 1,
                loader=loader, doc=doc, bindings=bindings, budget=budget,
            )
